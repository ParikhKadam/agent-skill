    W = lw + n * cw_ + 10
    H = 78 + len(rows) * rh + 40
    s = Svg('M', W, H, tx(texts, 'M', 'title', 'Permission grid'), tx(texts, 'M', 'desc', 'Actors by actions, coloured allowed, debug-switch only, or no.'))
    for j, h in enumerate(head[1:]):
        for k, l in enumerate(wrap(h, cw_ - 10, 5.7)[:3]):
            s.text(lw + j * cw_ + cw_ / 2, 18 + k * 12, l, 'ts2', 'middle')
    for i, r in enumerate(rows):
        y = 60 + i * rh
        for k, l in enumerate(wrap(r[0], lw - 16, 6.0)[:2]):
            s.text(8, y + 19 + k * 12 - (6 if len(wrap(r[0], lw - 16, 6.0)) > 1 else 0), l, 'ts2')
