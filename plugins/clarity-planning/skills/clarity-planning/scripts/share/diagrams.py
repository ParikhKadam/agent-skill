# ------------------------------------------------------------------ L risk grid
def short_title(r, short):
    if short.get(r['id']):
        return short[r['id']]
    t = r['text']
    return t if len(t) <= 34 else t[:33].rsplit(' ', 1)[0] + '...'


def diag_L(risks, short, texts=None):
    W, H = 980, 560
    s = Svg('L', W, H, tx(texts, 'L', 'title', 'Risk grid'), tx(texts, 'L', 'desc', 'Impact against uncertainty, with each risk placed and linked to its spike.'))
    gx, gy, cw_, ch = 90, 30, 290, 150
    s.text(gx + cw_ * 1.5, H - 14, 'Uncertainty (3 = we are guessing)  →', 'ts2', 'middle')
    s.raw('<text transform="translate(22 %g) rotate(-90)" class="ts2" text-anchor="middle">Impact (3 = worst)  →</text>' % (gy + ch * 1.5))
    for u in (1, 2, 3):
        for imp in (1, 2, 3):
            x = gx + (u - 1) * cw_
            y = gy + (3 - imp) * ch
            sc = imp * u
            s.rect(x, y, cw_ - 4, ch - 4, 'heat h%d' % (0 if sc <= 2 else 1 if sc <= 4 else 2), 6)
            s.text(x + 8, y + 14, 'score %d' % sc, 'ts')
    for u in (1, 2, 3):
        s.text(gx + (u - 1) * cw_ + cw_ / 2, gy + 3 * ch + 14, str(u), 'ts2', 'middle')
    for imp in (1, 2, 3):
        s.text(gx - 12, gy + (3 - imp) * ch + ch / 2, str(imp), 'ts2', 'end')
    cells = {}
    for r in risks:
        if 1 <= r['impact'] <= 3 and 1 <= r['unc'] <= 3:
            cells.setdefault((r['impact'], r['unc']), []).append(r)
    for (imp, u), rs in cells.items():
        x = gx + (u - 1) * cw_
        y = gy + (3 - imp) * ch + 22
        for k, r in enumerate(rs):
            yy = y + k * 17
            sp = ' '.join(r['spikes'])
            s.text(x + 8, yy + 10, r['id'], 'ts2')
            s.text(x + 44, yy + 10, short_title(r, short), 'ts')
            if sp:
                s.text(x + cw_ - 12, yy + 10, sp, 'ts', 'end')
    cap = tx(texts, 'L', 'caption', 'Generated from the Impact, Uncertainty and Plan columns of RISKS; the spike beside a risk is the one its plan names.')
    return s.render(cap, wide=900)


# ------------------------------------------------------------------ M permission grid
