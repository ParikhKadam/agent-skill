"""Diagrams. Drawn from the markdown where the facts are in tables (dependency map, timeline, status board, risk grid,
permission grid); drawn from authored data (html-src/authored.json) where they are not (system context, sequences, state
machine, failure tree, wireframe, journey, re-entry matrix, scope map). A missing authored diagram shows a visible placeholder."""
import re
from svgkit import Svg, wrap
from mdparse import esc

TRACK_CLASS = {}   # track letter -> svg class, set by the builder from the authored tracks (default: b, l, f in order)
PLACEHOLDER = 'not authored yet: see references/share-pages.md'


def legend(s, x, y, items):
    for lab, cls in items:
        s.rect(x, y - 10, 14, 14, 'nd ' + cls, 3)
        s.text(x + 20, y + 2, lab, 'ts')
        x += 26 + len(lab) * 6.2 + 14


def placeholder(key, what):
    """Visible marker for an authored diagram that has no data yet."""
    return ('<figure class="diagram" id="fig-%s" style="border:2px dashed var(--warn)"><p style="margin:8px 4px"><strong>%s</strong>: %s</p></figure>'
            % (esc(key), esc(what), PLACEHOLDER))


def tx(texts, key, field, default):
    return (texts or {}).get(key, {}).get(field, default)


# ------------------------------------------------------------------ authored drawings
def draw(spec, key):
    """Render a drawing authored as a list of primitive operations.
    spec = {w, h, title, desc, caption, wide, ops: [[op, [args], {kwargs}?], ...]}; op is a method of Svg
    (rect, text, node, poly, path, label, raw, lines). Points of poly are lists of [x, y]."""
    s = Svg(key, spec['w'], spec['h'], spec.get('title', ''), spec.get('desc', ''))
    for o in spec['ops']:
        name, args = o[0], list(o[1])
        kw = o[2] if len(o) > 2 else {}
        if name == 'poly':
            args[0] = [tuple(p) for p in args[0]]
        getattr(s, name)(*args, **kw)
    return s.render(spec.get('caption', ''), wide=spec.get('wide', 720))


# ------------------------------------------------------------------ B
def diag_B(comps, art_titles, art_part, edits, hub_id='', hub_label='', order=(), texts=None):
    order = list(order)
    comps = sorted(comps, key=lambda c: order.index(c['id']) if c['id'] in order else 99)
    arts = sorted(art_titles)
    H = 60 + len(arts) * 44 + (220 if edits else 70)
    s = Svg('B', 980, H, tx(texts, 'B', 'title', 'Dependency map'), tx(texts, 'B', 'desc', 'Which stored results each component reads and writes, and what an edit marks outdated.'))
    ax, aw, ah, ay0, ag = 20, 290, 36, 40, 44
    cx, cw_ = 640, 320
    ys = {}
    for i, a in enumerate(arts):
        y = ay0 + i * ag
        ys[a] = y
        part = art_part.get(a)
        s.node(ax, y, aw, ah, 'ng', a + ' ' + art_titles[a], ([('part: ' + part)] if part else []), anchor='start', tcls='ts2', wrap_lines=False)
    ch = 46
    cstep = (len(arts) * ag - 8 - ch) / max(1, len(comps) - 1)
    cy = {}
    for i, c in enumerate(comps):
        y = ay0 + i * cstep
        cy[c['id']] = y
        cls = TRACK_CLASS.get(c['side'], 'ng')
        s.node(cx, y, cw_, ch, cls, c['id'] + ' ' + c['title'], [c['owner']], anchor='start', tcls='ts2', wrap_lines=False)
    for c in comps:
        hub = bool(hub_id) and c['id'] == hub_id
        for a in c['reads']:
            if a in ys:
                x1, y1, x2, y2 = ax + aw, ys[a] + ah / 2, cx, cy[c['id']] + ch / 2 - 6
                s.path('M%g %g C%g %g %g %g %g %g' % (x1, y1, 470, y1, 480, y2, x2, y2), 'e eread' + (' hub' if hub else ''), 'r')
        for a in c['writes']:
            if a in ys:
                x1, y1, x2, y2 = cx, cy[c['id']] + ch / 2 + 6, ax + aw, ys[a] + ah / 2 + 4
                s.path('M%g %g C%g %g %g %g %g %g' % (x1, y1, 480, y1, 470, y2, x2, y2), 'e ewrite' + (' hub' if hub else ''), 'w')
    yb = ay0 + len(arts) * ag + 10
    if edits:
        s.text(20, yb + 8, 'What an edit marks outdated (never regenerated by itself)', 'tt')
    rows = edits
    for i, (src, dst) in enumerate(rows):
        y = yb + 22 + i * 34
        s.node(20, y, 330, 28, 'ng', src, [], anchor='start', tcls='ts2', wrap_lines=False)
        s.poly([(350, y + 14), (400, y + 14)], 'e eout', 'o')
        x = 410
        for d in dst:
            w = 14 + len(d) * 6.3
            s.node(x, y, w, 28, 'na', d, [], tcls='ts2', wrap_lines=False)
            x += w + 8
    legend_y = H - 14
    s.raw('<g>')
    s.poly([(20, legend_y - 4), (60, legend_y - 4)], 'e eread', 'r')
    s.text(66, legend_y, 'component reads', 'ts')
    s.poly([(190, legend_y - 4), (230, legend_y - 4)], 'e ewrite', 'w')
    s.text(236, legend_y, 'component writes', 'ts')
    if hub_id:
        s.text(360, legend_y, 'faint lines belong to %s, which touches most results' % (hub_label or hub_id), 'ts')
    s.raw('</g>')
    cap = tx(texts, 'B', 'caption', 'Generated from the Reads and Writes lines of the component cards and the artifact table.')
    return s.render(cap, wide=900)


# ------------------------------------------------------------------ sequences
def sequence(key, title, desc, lifelines, steps, caption, width=980):
    steps = [dict(st) for st in steps]
    lifelines = [(k, lab, cls) for k, lab, cls in lifelines]
    n = len(lifelines)
    lm = 90
    gap = (width - 2 * lm) / (n - 1) if n > 1 else 0
    xs = {k: lm + i * gap for i, (k, _, _) in enumerate(lifelines)}
    heights = []
    for st in steps:
        h = st.get('h', 34)
        if st['k'] == 'self':
            h = max(h, 12 * len(wrap(st['t'], 236, 5.9)) + 30)
        if st['k'] == 'msg':
            h = max(h, 40 + 12 * max(0, len(wrap(st['t'], 200, 6.0)) - 1))
        heights.append(h)
    total = 124 + sum(heights) + 40
    s = Svg(key, width, total, title, desc)
    for k, lab, cls in lifelines:
        s.node(xs[k] - 70, 8, 140, 62, cls, lab[0], lab[1:], tcls='ts2', scls='ts', lh=12.5)
        s.raw('<line x1="%g" y1="70" x2="%g" y2="%g" class="life"/>' % (xs[k], xs[k], total - 24))
    y = 124
    for st, h in zip(steps, heights):
        kind = st['k']
        if kind == 'msg':
            x1, x2 = xs[st['from']], xs[st['to']]
            cls = 'e ecb' if st.get('cb') else ('e eq' if st.get('q') else ('e edash' if st.get('ret') else 'e'))
            mk = 'cb' if st.get('cb') else ('q' if st.get('q') else ('g' if st.get('ret') else 'a'))
            d = 1 if x2 > x1 else -1
            s.poly([(x1 + 3 * d, y), (x2 - 3 * d, y)], cls, mk)
            mx = (x1 + x2) / 2
            ls = wrap(st['t'], min(abs(x2 - x1) - 10, 420) if abs(x2 - x1) > 100 else 200, 6.0)
            for i, l in enumerate(ls):
                s.label(mx, y - 6 - (len(ls) - 1 - i) * 12, l, 'tl')
        elif kind == 'self':
            x = xs[st['at']]
            s.rect(x + 6, y - 14, 250, 12 * len(wrap(st['t'], 236, 5.9)) + 8, 'nd na', 4)
            for i, l in enumerate(wrap(st['t'], 236, 5.9)):
                s.text(x + 14, y + 1 + i * 12, l, 'ts')
        elif kind == 'band':
            s.rect(14, y - 14, width - 28, 22, 'band', 4)
            s.text(24, y + 1, st['t'], 'ts2')
        y += h
    return s.render(caption)


def sequence_from(spec):
    """spec = {key, title, desc, lifelines: [[id, [label lines], class]], steps: [{k: msg|self|band, from, to, at, t, h, q, cb, ret}], caption, width}"""
    return sequence(spec['key'], spec.get('title', ''), spec.get('desc', ''), spec['lifelines'], spec['steps'], spec.get('caption', ''), spec.get('width', 980))


# ------------------------------------------------------------------ re-entry matrix (authored rows)
def diag_E(cols, rows, star_note='', texts=None):
    """rows = [[action, cells, note]]; cell letters: R reruns, O marked outdated, U untouched, o outdated if something changed."""
    rh, lw, cw_ = 30, 360, 112
    W = lw + cw_ * len(cols) + 330
    H = 70 + rh * len(rows) + 50
    s = Svg('E', W, H, tx(texts, 'E', 'title', 'Re-entry matrix'), tx(texts, 'E', 'desc', 'For each action, which parts rerun, are marked outdated, or are left untouched.'))
    for j, c in enumerate(cols):
        s.text(lw + j * cw_ + cw_ / 2, 48, c, 'tt', 'middle')
    s.text(lw + cw_ * len(cols) + 12, 48, 'note', 'tt')
    for i, (lab, cells, note) in enumerate(rows):
        y = 60 + i * rh
        if i % 2 == 0:
            s.rect(10, y, W - 20, rh, 'zebra', 0)
        for k, l in enumerate(wrap(lab, lw - 20, 6.0)[:2]):
            s.text(18, y + 13 + k * 11 if len(wrap(lab, lw - 20, 6.0)) > 1 else y + 19, l, 'ts')
        for j, ch in enumerate(cells):
            x = lw + j * cw_ + 6
            cls, txt = {'R': ('cr', 'reruns'), 'O': ('co', 'outdated'), 'U': ('cu', 'untouched'), 'o': ('co cond', 'outdated if changed')}[ch]
            s.rect(x, y + 3, cw_ - 12, rh - 6, 'cell ' + cls, 5)
            s.text(x + (cw_ - 12) / 2, y + 19, txt if ch != 'o' else 'outdated*', 'ts', 'middle')
        s.text(lw + cw_ * len(cols) + 12, y + 19, note, 'ts')
    ly = H - 16
    legend(s, 20, ly, [('reruns', 'cr'), ('marked outdated', 'co'), ('untouched', 'cu')])
    if star_note:
        s.text(330, ly + 2, star_note, 'ts')
    cap = tx(texts, 'E', 'caption', 'One row per action; the cells are authored from the flow documents.')
    return s.render(cap, wide=860)


# ------------------------------------------------------------------ G timeline (from the plan tables)
def diag_G(slices, ptitles, tracks, join_prefix='', freeze='', texts=None):
    """tracks = [[letter, label, svg class]]. Lanes: slices with no single known track, one lane per track, then join slices."""
    phases = sorted(set(sl['phase'] for sl in slices))
    p0, p1 = phases[0], phases[-1]
    plist = list(range(p0, p1 + 1))
    lanes = [('shared', 'All tracks')] + [(t[0], t[1]) for t in tracks] + ([('J', 'Join slices')] if join_prefix else [])
    known = {t[0] for t in tracks}

    def lane_of(sl):
        if join_prefix and sl['id'].startswith(join_prefix):
            return 'J'
        return sl['track'] if sl['track'] in known else 'shared'
    cell = {}
    for sl in slices:
        cell.setdefault((lane_of(sl), sl['phase']), []).append(sl)
    lanes = [(ln, lab) for ln, lab in lanes if any(lane_of(sl) == ln for sl in slices)]
    cls_of = {t[0]: t[2] for t in tracks}
    lw, cwid, bh = 96, 172, 52
    heights = {}
    for ln, _ in lanes:
        m = max([len(cell.get((ln, p), [])) for p in plist] + [1])
        heights[ln] = m * (bh + 6) + 10
    top = 62
    H = top + sum(heights.values()) + 30
    W = lw + cwid * len(plist) + 10
    s = Svg('G', W, H, tx(texts, 'G', 'title', 'Timeline of phases and tracks'),
            tx(texts, 'G', 'desc', 'Phases as columns, tracks as lanes, slices as boxes, join slices as markers.'))
    for n, p in enumerate(plist):
        x = lw + n * cwid
        s.rect(x + 2, 6, cwid - 4, 44, 'nd ng', 6)
        s.text(x + cwid / 2, 24, 'Phase %d' % p, 'tt', 'middle')
        t = ptitles.get(p, '')
        t = re.sub(r'\(.*\)', '', t).strip()
        for k, l in enumerate(wrap(t, cwid - 14, 5.7)[:2]):
            s.text(x + cwid / 2, 37 + k * 11, l, 'ts', 'middle')
    y = top
    for ln, lab in lanes:
        h = heights[ln]
        s.rect(4, y, W - 8, h, 'lane lane-' + ln, 4)
        s.text(10, y + 18, lab, 'tt')
        for n, p in enumerate(plist):
            items = cell.get((ln, p), [])
            for k, sl in enumerate(items):
                bx, by = lw + n * cwid + 6, y + 6 + k * (bh + 6)
                cls = cls_of.get(ln, 'ng')
                if ' and ' in sl['track']:
                    cls = 'nbl'
                if ln == 'J':
                    s.raw('<polygon points="%g,%g %g,%g %g,%g %g,%g" class="nd nj"/>' % (bx + 8, by + bh / 2, bx + 8 + 18, by, bx + 8 + 36, by + bh / 2, bx + 8 + 18, by + bh))
                    s.text(bx + 52, by + 17, sl['id'], 'ts2')
                    s.text(bx + 52, by + 30, 'join', 'ts')
                else:
                    s.rect(bx, by, cwid - 12, bh, 'nd ' + cls, 6)
                    s.text(bx + 8, by + 15, sl['id'], 'ts2')
                    tt = re.sub(r'\s*\(.*?\)', '', sl['title'])
                    for q, l in enumerate(wrap(tt, cwid - 24, 5.6)[:2]):
                        s.text(bx + 8, by + 29 + q * 11, l, 'ts')
        y += h
    if freeze:
        fx = lw + cwid - 2
        s.raw('<line x1="%g" y1="%g" x2="%g" y2="%g" class="freeze"/>' % (fx, 52, fx, H - 22))
        s.text(fx + 4, H - 8, freeze, 'ts')
    cap = tx(texts, 'G', 'caption', 'Generated from the phase tables of PLAN (one box per slice, in plan order within a phase).')
    return s.render(cap, wide=900)


